/** a random line of category `cat` in the current language (null when there is none) */
export function line(cat, rnd) {
  const tb = (LINES[current] || LINES.ko)[cat] || LINES.ko[cat];
  if (!tb || !tb.length) return null;
  const r = rnd !== undefined ? rnd : Math.random();
  return tb[Math.floor(r * tb.length) % tb.length];
}

