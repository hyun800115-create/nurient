export function t(key, params) {
  const table = STRINGS[current] || STRINGS.ko;
  let s = table[key];
  if (s === undefined) s = STRINGS.ko[key];
  if (s === undefined) return key;
  if (params) for (const k in params) s = s.split('{' + k + '}').join(String(params[k]));
  return s;
}


