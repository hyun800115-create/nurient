let current = 'ko';

export function detectLang() {
  try {
    const nav = (navigator.language || navigator.userLanguage || 'ko').toLowerCase();
    return nav.startsWith('ko') ? 'ko' : 'en';
  } catch (e) { return 'ko'; }
}

export function setLang(l) { current = STRINGS[l] ? l : 'ko'; }
export function getLang() { return current; }

export function t(key, params) {
  const table = STRINGS[current] || STRINGS.ko;
  let s = table[key];
  if (s === undefined) s = STRINGS.ko[key];
  if (s === undefined) return key;
  if (params) {
    for (const k in params) {
      const v = String(params[k]);
      // (v4.2) Korean particles after a value: {item|이/가}, {name|을/를}, {place|(으)로} …
      if (s.indexOf('{' + k + '|') >= 0) s = s.replace(new RegExp('\\{' + k + '\\|([^}]+)\\}', 'g'), (m, pair) => v + josa(v, pair));
      s = s.split('{' + k + '}').join(v);
    }
  }
  // (v4.2) the same particles written after a filled-in word: "…이(가)" "을(를)" "(으)로" "와(과)"
  if (s.indexOf(')') >= 0) s = s.replace(/([가-힣A-Za-z0-9])(이\(가\)|을\(를\)|은\(는\)|와\(과\)|\(으\)로)/g, (m, ch, p) => ch + josa(ch, { '이(가)': '이/가', '을(를)': '을/를', '은(는)': '은/는', '와(과)': '과/와', '(으)로': '(으)로' }[p]));
  return s;
}

/** (v4.2) the Korean particle after `word` for a pair '이/가' | '을/를' | '은/는' | '과/와' | '(으)로' (batchim rule) */
export function josa(word, pair) {
  const w = String(word || '');
  const c = w.charCodeAt(w.length - 1);
  let fin = -1;
  if (c >= 0xac00 && c <= 0xd7a3) fin = (c - 0xac00) % 28;
  else if (/[0-9]$/.test(w)) fin = '0136781'.indexOf(w[w.length - 1]) >= 0 ? (w.endsWith('1') || w.endsWith('7') || w.endsWith('8') ? 8 : 1) : 0;
  else fin = 0;
  if (pair === '(으)로') return fin > 0 && fin !== 8 ? '으로' : '로';
  const [a, b] = pair.split('/');
  return fin > 0 ? a : b;
}


