def quantize(sheet):
    import imagequant
    return imagequant.quantize_pil_image(sheet, dithering_level=0.6, max_quality=100, min_quality=0, max_colors=256)


def pack_groups(groups):
    out = []
    for g in ATLAS_ORDER + sorted(set(groups) - set(ATLAS_ORDER)):
        if g not in groups:
            continue
        builds = sorted(groups[g], key=lambda fr: -sum(im.width * im.height for _, im in fr))
        sheets = []
        for fr in builds:
            placed = False
            for sh in sheets:
                sheet, _ = pu.pack_atlas(sh + fr, max_width=MAX_SHEET, trim=True, padding=2)
                if sheet.height <= MAX_SHEET:
                    sh.extend(fr)
                    placed = True
                    break
            if not placed:
                sheets.append(list(fr))
        for i, sh in enumerate(sheets):
            sheet, atlas = pu.pack_atlas(sh, max_width=MAX_SHEET, trim=True, padding=2)
            out.append((g if i == 0 else '%s_%d' % (g, i + 1), sheet, atlas))
    return out


def guard(cache, have, need, allow_partial):
    have = set(have)
    if not have:
        raise SystemExit('civ_pack: ABORT - no complete renders in the cache %s; nothing was written (an empty '
                         'manifest is never written). Run civ_render.py first. / 렌더 캐시가 비어 있습니다.' % cache)
    missing = sorted(set(need) - have)
    if not missing:
        return []
    if allow_partial:
        print('civ_pack: WARNING --allow-partial: dropping %d key(s) not in the cache: %s' % (len(missing),
                                                                                           ' '.join(missing)))
        return missing
    raise SystemExit('civ_pack: ABORT - %d key(s) of the current manifest / civ_check.REQUIRED are missing from the '
                     'render cache %s; packing now would DELETE them. Nothing was written.\n    %s\n  fix: '
                     '/tmp/bvenv/bin/python tools/blender/civ_render.py -- <keys>  (or --allow-partial) / '
                     '캐시에 없는 키가 있어 중단합니다.' % (len(missing), cache, ' '.join(missing)))


def main(argv=None):
    argv = list(sys.argv[1:] if argv is None else argv)
    cache = os.path.join(tempfile.gettempdir(), 'fv_cache', 'civic')
    mode, previews, partial = 'on', True, False
    out_dir, prev_dir = OUT, PREV
    i = 0
    while i < len(argv):
        a = argv[i]
        if a == '--cache':
            cache = argv[i + 1]
            i += 1
        elif a == '--quantize':
            mode = argv[i + 1]
            i += 1
        elif a == '--no-previews':
            previews = False
        elif a == '--allow-partial':
            partial = True
        elif a == '--out':
            out_dir = argv[i + 1]
            i += 1
        elif a == '--prev':
            prev_dir = argv[i + 1]
            i += 1
        i += 1
    builds, vehicles = load(cache)
    import civ_decals as CD
    decals = CD.make_all()
    have = set(vehicles) | set(decals)
    for k, m in builds.items():
        have.add(k)
        have |= set((m.get('sprites') or {}).keys())
        if m.get('cutaway'):
            have |= {'%s_%s' % (k, lay) for lay in m['cutaway']['layers']}
        have |= {'%s_%s' % (k, n) for n in m.get('overlays', {})}
    have.add('furniture_pile')
    import civ_check as cc
    man_path = os.path.join(out_dir, 'manifest.json')
    old = json.load(open(man_path)) if os.path.exists(man_path) else None
    in_manifest = set((old or {}).get('characters', {})) | set((old or {}).get('sprites', {}))
    guard(cache, have, in_manifest | set(cc.REQUIRED), partial)
    # ---- images
    frames, groups = {}, {}
    for k, m in builds.items():
        imgs = build_images(cache, m)
        if m.get('cutaway'):
            m['revealPoly'] = reveal_poly(imgs['%s_shell' % k], m['anchorPx'])
        frames.update(imgs)
        groups.setdefault(m['atlas'], []).append(list(imgs.items()))
    for k, (im, meta) in decals.items():
        frames[k] = im
        groups.setdefault('civ_decals', []).append([(k, im)])
    sheets = pack_groups(groups)
    vimgs = {}
    for k in VEH_KEYS:
        if k in vehicles:
            vimgs[k] = veh_images(cache, k, vehicles[k])
            sheet, atlas = pu.pack_atlas(list(vimgs[k].items()), max_width=MAX_SHEET, trim=True, padding=2)
            sheets.append(('civ_' + k, sheet, atlas))
    for akey, sheet, atlas in sheets:
        if sheet.width > MAX_SHEET or sheet.height > MAX_SHEET:
            raise SystemExit('civ_pack: atlas %s is %dx%d (> %d)' % (akey, sheet.width, sheet.height, MAX_SHEET))
    os.makedirs(out_dir, exist_ok=True)
    for fn in os.listdir(out_dir):
        if fn.startswith('civ_') and fn.endswith(('.png', '.json')):
            os.remove(os.path.join(out_dir, fn))
    total = 0
    fa = {}
    for akey, sheet, atlas in sheets:
        png = os.path.join(out_dir, akey + '.png')
        jsn = os.path.join(out_dir, akey + '.json')
        pu.save_atlas(sheet, atlas, png, jsn, quantize=False)
        if mode in ('on', 'auto'):
            try:
                quantize(sheet).save(png, optimize=True)
            except ImportError:
                print('  imagequant not installed -> kept RGBA (pip install imagequant)')
        sz = os.path.getsize(png) + os.path.getsize(jsn)
        total += sz
        for n in atlas['frames']:
            fa[n] = akey
        print('%-18s %4dx%-4d %3d frames %7.1f KB' % (akey, sheet.width, sheet.height, len(atlas['frames']),
                                                     sz / 1024.0))
    # ---- manifest
    sprites, chars = {}, {}
    order = sorted(builds, key=lambda k: (ATLAS_ORDER.index(builds[k]['atlas']) if builds[k]['atlas'] in ATLAS_ORDER
                                          else 99, k))
    for k in order:
        sprites.update(entries_for(k, builds[k], fa))
    if 'furniture_pile_l' in sprites:
        sprites['furniture_pile'] = dict(sprites['furniture_pile_l'], aliasOf='furniture_pile_l')
    for k, (im, meta) in decals.items():
        sprites[k] = {'atlas': fa[k], 'frame': k, 'anchor': meta['anchor'], 'frameSize': meta['frameSize'],
                      'kind': 'decal', 'footprint': meta['footprint'], 'radiusM': meta['radiusM'],
                      'plotM': meta['plotM'], 'layer': 'ground', 'zone': 'ruins',
                      'name': {'ko': '그을음 자국 (%s)' % k[-1].upper(), 'en': 'Scorch decal %s' % k[-1].upper()},
                      'notes': ('Soot-stained snow of a burnt %s plot (procedural): soft charcoal smudge, wet '
                                'melted ring, ash flecks. Ground layer under ruin_%s / rubble / the site; fade it out '
                                'slowly after the rebuild.' % (k[-1].upper(), k[-1]))}
    for k in VEH_KEYS:
        if k in vehicles:
            chars[k] = veh_entry(k, vehicles[k], 'civ_' + k)
            chars[k]['name'] = {'excavator': {'ko': '굴착기', 'en': 'Excavator'},
                                'dump_truck': {'ko': '덤프트럭', 'en': 'Dump truck'}}[k]
            chars[k]['zone'] = 'demolition'
    man = dict(old) if old else {}
    man['version'] = 1
    man['generator'] = 'tools/blender/civ_render.py + civ_pack.py (docs/CONTRACT_V8.md section AB)'
    man['conventions'] = CONVENTIONS
    man['atlases'] = [{'key': a, 'png': 'civic/%s.png' % a, 'json': 'civic/%s.json' % a} for a, _, _ in sheets]
    oldsp, oldch = (old or {}).get('sprites', {}), (old or {}).get('characters', {})
    man['sprites'] = {k: dict(oldsp.get(k, {}), **v) for k, v in sprites.items()}
    man['characters'] = {k: dict(oldch.get(k, {}), **v) for k, v in chars.items()}
    man['fenceRings'] = fence_rings()
    man['demolitionLayout'] = demolition_layout(vehicles)
    man['fireSequence'] = FIRE_SEQUENCE
    if not man['sprites'] and not man['characters']:
        raise SystemExit('civ_pack: refusing to write an empty manifest')
    with open(man_path, 'w') as f:
        json.dump(man, f, indent=1, ensure_ascii=False)
    total += os.path.getsize(man_path)
    print('assets/civic: %d sprites, %d vehicles, %d atlases, payload %.2f MB (budget %.1f MB)'
          % (len(man['sprites']), len(man['characters']), len(sheets), total / 1048576.0, BUDGET_MB))
    if previews:
        import civ_preview as cp
        cp.make_all(out_dir, prev_dir)


if __name__ == '__main__':
    main()
