def iso(x, y, z=0.0):
    return [int(round((x + y) * PX_X)), int(round((x - y) * PX_Y - z * 55.4256))]


def fence_rings():
    """Ready-made demolition fence rings around S / M / L plots: n tiles of sqrt(2) m per side (2 / 3 / 4), offsets
    in px from the plot centre (= the ruin / site anchor).  Back edges first (draw order = y-sort anyway)."""
    out = {}
    for sz, n in (('S', 2), ('M', 3), ('L', 4)):
        h = n * SQ2 / 2
        ring = []
        for k in range(n):
            c = -h + SQ2 / 2 + k * SQ2
            ring.append({'key': 'demolition_fence_x' + ('_lamp' if k == n // 2 else ''), 'at': iso(c, h)})
            ring.append({'key': 'demolition_fence_y', 'at': iso(-h, c)})
            ring.append({'key': 'demolition_fence_y' + ('_lamp' if k == n // 2 else ''), 'at': iso(h, c)})
            ring.append({'key': 'demolition_fence_x', 'at': iso(c, -h)})
        ring.append({'key': 'demolition_fence_post', 'at': iso(h, h)})
        out[sz] = {'sideM': round(n * SQ2, 3), 'tilesPerSide': n, 'pieces': ring,
                   'gate': 'leave out one front demolition_fence_x piece for a walk-in gap'}
    return out


def to_world(dx, dy):
    return (dx / PX_X + dy / PX_Y) / 2.0, (dx / PX_X - dy / PX_Y) / 2.0


