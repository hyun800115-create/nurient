"""
civ_pack.py - turn the raw civic renders (civ_render.py cache) into assets/civic/: trimmed Phaser atlases (each sheet
<= 2048 px, palettised with libimagequant) + manifest.json, then the previews (civ_preview.py).

No Blender needed: python3 with numpy + Pillow (+ `imagequant`).
    python3 tools/blender/civ_pack.py [--cache DIR] [--quantize on|auto|off] [--no-previews] [--allow-partial]
                                      [--out DIR] [--prev DIR]        (dry runs: write somewhere else)

Guard + merge (like bld_pack / town_pack / veh_pack): the packer MERGES into the existing assets/civic/manifest.json
(unknown top-level fields and extra fields inside entries are kept, generated fields win) and REFUSES (exit 1, nothing
written) when a key of the current manifest or of civ_check.REQUIRED has no complete render in the cache, because
rebuilding the atlases would drop it.  --allow-partial packs what is cached.  An empty manifest is never written.

Steps
  1. plain builds: <cache>/<build>.json sidecars (bld_render format).  Shadow-caught frames get the village-building
     post (pack_utils.clean_alpha + prop_pack.tint_shadow + prop_pack.border_fade); fence tiles get a
     partition-of-unity cut of their (continuous) shadow instead of the border fade; overlay frames (ruin smoke) only
     clean_alpha.
  2. cutaway builds (bank, police_station): the ground-shadow pass is merged UNDER the floor layer; the closed
     building (<key>) is composited from all layers (overlays at frame 0); revealPoly = convex hull of the shell.
  3. vehicles: <cache>/<key>/meta.json + frames, the characters' 1 px ink outline (char_pack.ink_outline).
  4. scorch decals: generated by civ_decals.py (procedural, deterministic).
  5. atlases: civ_bank, civ_police, civ_ruins, civ_props, civ_moving, civ_demo, civ_decals (+ _2 .. at 2048 px; a
     build's frames always share a sheet), civ_excavator, civ_dump_truck.
  6. manifest: sprites{} + characters{} (vehicles) + fenceRings + demolitionLayout + fireSequence + conventions.
"""
