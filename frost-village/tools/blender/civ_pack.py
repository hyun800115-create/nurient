def footprint_poly(m):
    fm = m.get('footprintM')
    if not isinstance(fm, list) or len(fm) != 2:
        return None
    a, b = fm
    yaw = math.radians(m.get('yaw', 0.0))
    pts = []
    for lx, ly in ((-a / 2, -b / 2), (a / 2, -b / 2), (a / 2, b / 2), (-a / 2, b / 2)):
        x = lx * math.cos(yaw) - ly * math.sin(yaw)
        y = lx * math.sin(yaw) + ly * math.cos(yaw)
        pts.append([int(round((x + y) * PX_X)), int(round((x - y) * PX_Y))])
    return pts


def hull(points):
    pts = sorted(set(points))
    if len(pts) < 3:
        return pts

    def cross(o, a, b):
        return (a[0] - o[0]) * (b[1] - o[1]) - (a[1] - o[1]) * (b[0] - o[0])
    lo, up = [], []
    for p in pts:
        while len(lo) >= 2 and cross(lo[-2], lo[-1], p) <= 0:
            lo.pop()
        lo.append(p)
    for p in reversed(pts):
        while len(up) >= 2 and cross(up[-2], up[-1], p) <= 0:
            up.pop()
        up.append(p)
    return lo[:-1] + up[:-1]


def simplify(poly, n=10):
    poly = list(poly)
    while len(poly) > n:
        best, bi = None, 0
        for i in range(len(poly)):
            a, b, c = poly[i - 1], poly[i], poly[(i + 1) % len(poly)]
            area = abs((b[0] - a[0]) * (c[1] - a[1]) - (c[0] - a[0]) * (b[1] - a[1]))
            if best is None or area < best:
                best, bi = area, i
        poly.pop(bi)
    return poly


def reveal_poly(img, anchor):
    a = np.asarray(img)[..., 3]
    ys, xs = np.nonzero(a > 140)
    if not len(xs):
        return []
    # boundary samples: per row extremes
    pts = []
    for y in np.unique(ys)[::2]:
        row = xs[ys == y]
        pts += [(int(row.min()), int(y)), (int(row.max()), int(y))]
    poly = simplify(hull(pts), 10)
    return [[int(x - anchor[0]), int(y - anchor[1])] for x, y in poly]


def put_points(s, pts, dirs):
    for kind, field in POINT_SINGLE.items():
        if pts.get(kind):
            s[field] = pts[kind][0]
            if dirs.get(kind) and kind not in NO_DIR:
                s[dir_field(field)] = dirs[kind][0]
    for kind, field in POINT_LIST.items():
        if pts.get(kind):
            s[field] = pts[kind]
            if dirs.get(kind) and kind not in NO_DIR:
                s[dir_field(field)] = dirs[kind]


def base_entry(m, frame, atlas):
    s = {'atlas': atlas, 'frame': frame, 'anchor': m['anchor'], 'frameSize': m['frameSize'], 'kind': m['kind']}
    if 'footprint' in m:
        s['footprint'] = m['footprint']
        s['footprintM'] = m['footprintM']
    poly = footprint_poly(m)
    if poly and not m.get('tileAxis'):
        s['footprintPoly'] = poly
    tops = m.get('topPx', {})
    s['topPx'] = tops.get(frame, next(iter(tops.values()))) if isinstance(tops, dict) and tops else tops
    if m.get('front'):
        s['front'] = m['front']
    for f in ('name', 'zone'):
        if f in m:
            s[f] = m[f]
    return s


