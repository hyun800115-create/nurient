def shadow_post(im):
    return pp.border_fade(pp.tint_shadow(pu.clean_alpha(im, floor=10)))


def tile_shadow_seg(img, anchor, axis, seg, h=0.14):
    """Partition-of-unity cut of the SHADOW pixels of a tile rendered with shadow-only neighbours (prop_pack.
    tile_shadow generalised to any segment length): w(u) + w(u - seg) = 1, a' = 1 - (1 - a)^w."""
    a = np.asarray(img.convert('RGBA')).astype(np.float32)
    H, W = a.shape[:2]
    ax, ay = anchor
    px, py = np.meshgrid(np.arange(W) + 0.5 - ax, np.arange(H) + 0.5 - ay)
    gx = (px / PX_X + py / PX_Y) / 2.0
    gy = (px / PX_X - py / PX_Y) / 2.0
    u = np.abs(gx if axis == 'x' else gy)
    w = np.clip(0.5 + (seg / 2.0 - u) / (2 * h), 0.0, 1.0)
    alpha = a[..., 3] / 255.0
    lum = a[..., :3].mean(-1)
    m = np.clip(1.0 - lum / 70.0, 0.0, 1.0) * (a[..., 3] < 252)
    new = 1.0 - np.power(np.clip(1.0 - alpha, 1e-6, 1.0), w)
    alpha = alpha * (1 - m) + new * m
    a[..., 3] = np.clip(alpha * 255.0, 0, 255)
    a[a[..., 3] < 1] = 0
    return Image.fromarray(a.astype(np.uint8), 'RGBA')


def load(cache):
    builds, vehicles = {}, {}
    if not os.path.isdir(cache):
        return builds, vehicles
    for fn in sorted(os.listdir(cache)):
        p = os.path.join(cache, fn)
        if os.path.isdir(p) and os.path.exists(os.path.join(p, 'meta.json')):
            m = json.load(open(os.path.join(p, 'meta.json')))
            names = ['%s_%s_%d' % (a, d, i) for a, info in m['anims'].items() for d in m['dirs']
                     for i in range(info['frames'])]
            if all(os.path.exists(os.path.join(p, n + '.png')) for n in names):
                m['names'] = names
                vehicles[fn] = m
            else:
                print('note: vehicle %s has missing frames - not packed' % fn)
        elif fn.endswith('.json'):
            try:
                m = json.load(open(p))
            except Exception:
                continue
            if 'build' not in m or 'frames' not in m:
                continue
            need = list(m['frames']) + [f for ov in m.get('overlays', {}).values() for f in ov['frames']]
            if all(os.path.exists(os.path.join(cache, n + '.png')) for n in need):
                builds[m['build']] = m
            else:
                print('note: %s has missing frames - not packed' % m['build'])
    return builds, vehicles


def build_images(cache, m):
    """{frame name -> post-processed RGBA} for one build (cutaway: + the composited closed frame)."""
    key = m['build']
    out = {}

    def raw(n):
        return Image.open(os.path.join(cache, n + '.png')).convert('RGBA')
    if m.get('cutaway'):
        ground = shadow_post(raw(m['cutaway']['ground']))
        layers = {}
        for lay in m['cutaway']['layers']:
            layers[lay] = pu.clean_alpha(raw('%s_%s' % (key, lay)), floor=3)
        floor = ground.copy()
        if 'floor' in layers:
            floor.alpha_composite(layers['floor'])
        layers['floor'] = floor
        for lay, im in layers.items():
            out['%s_%s' % (key, lay)] = im
        ov_imgs = {}
        for name, ov in m.get('overlays', {}).items():
            for f in ov['frames']:
                ov_imgs[f] = pu.clean_alpha(raw(f), floor=3)
                out[f] = ov_imgs[f]
        closed = floor.copy()
        for lay in draw_layers(m):
            if lay.startswith('@'):
                continue
            if lay in m.get('overlays', {}):
                closed.alpha_composite(ov_imgs[m['overlays'][lay]['frames'][0]])
            elif lay != 'floor' and lay in layers and lay != 'shell_cut':
                closed.alpha_composite(layers[lay])
        out[key] = closed
        return out
    tile = m.get('tileAxis')
    for n in m['frames']:
        im = raw(n)
        if not m.get('shadow', True):
            im = pu.clean_alpha(im, floor=3)
        elif tile:
            im = pp.tint_shadow(tile_shadow_seg(pu.clean_alpha(im, floor=10), m['anchorPx'], tile, m['segM']))
        else:
            im = shadow_post(im)
        out[n] = im
    for name, ov in m.get('overlays', {}).items():
        for f in ov['frames']:
            out[f] = pu.clean_alpha(raw(f), floor=3)
    return out


def draw_layers(m):
    """Game draw order for a cutaway build: layer names + '@behind' / '@front' character slots."""
    order = ['floor', 'back', 'interior', '@behind', 'front', '@front', 'shell_cut', 'shell']
    for name, ov in m.get('overlays', {}).items():
        after = ov.get('drawAfter', 'interior')
        idx = order.index('interior') + 1 if after == 'interior' else order.index('front') + 1
        order.insert(idx, name)
    return [x for x in order if x.startswith('@') or x in m['cutaway']['layers'] or x in m.get('overlays', {})]


